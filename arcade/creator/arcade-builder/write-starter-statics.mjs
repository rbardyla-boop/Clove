#!/usr/bin/env node
/**
 * Curated Starter Statics writer — AUTHOR-TIME dev tool (ADR-043; never ships).
 *
 * Materializes the curated floor set's per-starter files into
 * arcade/cabinets/starters/<id>/{game.mjs, adapter.mjs} so production needs NO
 * runtime import of arcade/creator/**:
 *   - game.mjs    = buildStarterPackage(id).files['game.mjs']  (the closed-table CF-4 game)
 *   - adapter.mjs = floorAdapterSource(entry)                  (deterministic wrapper template)
 *
 * This file lives under arcade/creator/ ON PURPOSE: the curated-upload denylist
 * excludes it from production, and the byte-match unit test re-derives both
 * outputs to prove the checked-in copies were generated here and never hand-edited.
 *
 *     node arcade/creator/arcade-builder/write-starter-statics.mjs
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildStarterPackage, STARTERS, INPUT_MODE_COPY } from './cabinet-templates.mjs';
import { CURATED_STARTERS } from '../../cabinets/starters/curated-floor.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');

/** PURE: the per-starter floor adapter module (import-loader contract; deterministic). */
export function floorAdapterSource(entry) {
  const lib = STARTERS.find((s) => s.id === entry.starter_id);
  const instruction = (lib && INPUT_MODE_COPY[lib.params.input_mode]) || INPUT_MODE_COPY.tap_window;
  return [
    '/** Generated by write-starter-statics (ADR-043) — curated starter floor adapter.',
    ' * client_local_only · ticket_mode none · no messages, no awards, no authority.',
    ' * BYTE-PINNED to the generator by unit test — do not hand-edit. */',
    "import { createGame as createCabinetGame } from './game.mjs';",
    "import { starterAdapter, starterContract, createStarterHostGame } from '../starter-host.mjs';",
    '',
    "export const adapter = starterAdapter('" + entry.game_id + "', '" + entry.label + "');",
    "export const contract = starterContract('" + entry.game_id + "', '" + entry.label + "');",
    'export function createGame(opts) {',
    "  return createStarterHostGame({ createCabinetGame, displayName: '" + entry.label + "', instruction: '" + instruction + "', sound: 'off', onLeave: opts && opts.onLeave });",
    '}',
    '',
  ].join('\n');
}

const isMain = process.argv[1] && import.meta.url === new URL('file://' + process.argv[1]).href;
if (isMain) {
  for (const entry of CURATED_STARTERS) {
    const pkg = buildStarterPackage(entry.starter_id);
    if (!pkg) { console.error(`UNKNOWN STARTER: ${entry.starter_id}`); process.exit(1); }
    const dir = join(ROOT, 'arcade', 'cabinets', 'starters', entry.starter_id);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, 'game.mjs'), pkg.files['game.mjs'] + '\n');
    writeFileSync(join(dir, 'adapter.mjs'), floorAdapterSource(entry));
    console.log(`wrote ${entry.starter_id}/ (game ${pkg.files['game.mjs'].length}B)`);
  }
  console.log(`${CURATED_STARTERS.length} curated starter statics regenerated — byte-stable, lab-free, no creator import in output`);
}
